import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import * as THREE from 'three';
import { runtimeBuildChunks } from './build/runtime-chunks.mjs';

const source = readFileSync(new URL('../assets/js/runtime/master/vrodos_gradient_sky.js', import.meta.url), 'utf8');
const context = vm.createContext({ THREE, VRODOSMaster: {} });
vm.runInContext(source, context);
const { ensureVrTakramLightsOnlyGradientSky: ensure, removeVrTakramLightsOnlyGradientSky: remove } = context.VRODOSMaster.GradientSky;
for (const invalid of [null, {}, { el: {} }]) {
    assert.equal(ensure(invalid, 'clear'), null);
    remove(invalid);
}
const noThree = vm.createContext({ VRODOSMaster: {} });
vm.runInContext(source, noThree);
assert.equal(noThree.VRODOSMaster.GradientSky.ensureVrTakramLightsOnlyGradientSky({ el: { object3D: new THREE.Group() } }), null);
const self = { el: { object3D: new THREE.Group() } };
const sky = ensure(self, 'clear');
assert.ok(sky instanceof THREE.Mesh);
assert.equal(self._vrTakramLightsOnlyGradientSky, sky);
assert.equal(sky.parent, self.el.object3D);
assert.equal(sky.geometry.parameters.radius, 4000);
assert.equal(sky.geometry.parameters.widthSegments, 32);
assert.equal(sky.geometry.parameters.heightSegments, 16);
assert.equal(sky.material.side, THREE.BackSide);
for (const property of ['depthWrite', 'depthTest', 'fog', 'toneMapped']) assert.equal(sky.material[property], false);
assert.equal(sky.frustumCulled, false);
assert.equal(sky.renderOrder, -1000);
assert.equal(sky.castShadow, false);
assert.equal(sky.receiveShadow, false);
assert.equal(sky.userData.vrodosVrTakramLightsOnlySky, true);
const hits = [];
sky.raycast(new THREE.Raycaster(), hits);
assert.deepEqual(hits, [], 'sky must not participate in selection');
const geometry = sky.geometry;
const material = sky.material;
const uniforms = material.uniforms;
for (const [preset, top, horizon] of [['clear', '#82c7fb', '#fff0d3'], ['crisp', '#8fc8f6', '#fff1d8'], ['natural', '#94c9f5', '#ffefd8'], ['unknown', '#94c9f5', '#ffefd8']]) {
    sky.visible = false;
    assert.equal(ensure(self, preset), sky);
    assert.equal(sky.geometry, geometry);
    assert.equal(sky.material, material);
    assert.equal(material.uniforms, uniforms);
    assert.ok(uniforms.topColor.value.equals(new THREE.Color(top)));
    assert.ok(uniforms.horizonColor.value.equals(new THREE.Color(horizon)));
    assert.ok(uniforms.bottomColor.value.equals(new THREE.Color('#f8fbff')));
    assert.equal(sky.visible, true);
    assert.equal(self.el.object3D.children.length, 1);
}
const oldParent = self.el.object3D;
self.el.object3D = new THREE.Group();
assert.equal(ensure(self, 'clear'), sky);
assert.equal(oldParent.children.length, 0);
assert.equal(sky.parent, self.el.object3D);
const other = { el: { object3D: new THREE.Group() } };
const otherSky = ensure(other, 'crisp');
assert.notEqual(otherSky.geometry, geometry);
assert.notEqual(otherSky.material, material);
const events = [];
geometry.addEventListener('dispose', () => { assert.equal(sky.parent, null); events.push('geometry'); });
material.addEventListener('dispose', () => events.push('material'));
remove(self);
assert.deepEqual(events, ['geometry', 'material']);
assert.equal(self._vrTakramLightsOnlyGradientSky, null);
assert.equal(self.el.object3D.children.length, 0);
remove(self);
assert.deepEqual(events, ['geometry', 'material'], 'repeated removal must not dispose twice');
assert.equal(otherSky.parent, other.el.object3D, 'removal must not affect other scenes');
const recreated = ensure(self, 'natural');
assert.notEqual(recreated, sky);
assert.notEqual(recreated.geometry, geometry);
remove(self);
remove(other);
remove({ _vrTakramLightsOnlyGradientSky: {} });
const core = runtimeBuildChunks.find(chunk => chunk.id === 'core-runtime');
const index = core.sourceFiles.indexOf('assets/js/runtime/master/vrodos_gradient_sky.js');
assert.ok(index >= 0 && index < core.sourceFiles.indexOf('assets/js/runtime/master/vrodos_quality_profiles.js'));
console.log('Gradient sky presets, reuse, scene isolation, and disposal tests passed.');
