import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

let now = 1000;
const context = vm.createContext({ VRODOSMaster: {}, performance: { now: () => now } });
vm.runInContext(readFileSync(new URL('../assets/js/runtime/master/vrodos_celestial_clock.js', import.meta.url), 'utf8'), context);
const clock = context.VRODOSMaster.CelestialClock;
const base = new Date('2026-09-11T18:00:00Z');
const component = { _pmndrsTickTimeMs: 1000 };
const run = (date = base, duration = 1) => clock.effectiveDate(component, date, duration).toISOString();
assert.equal(clock.minDurationMinutes, 0.25);
assert.equal(run(), base.toISOString());
component._pmndrsTickTimeMs += 30000;
assert.equal(run(), '2026-09-11T06:00:00.000Z', 'Solar time wraps inside the authored day.');
assert.equal(component._pmndrsDayNightCycleState.moonEffectiveDate.toISOString(), '2026-09-12T06:00:00.000Z');
component._pmndrsTickTimeMs += 150000;
assert.equal(run(), base.toISOString());
assert.equal(component._pmndrsDayNightCycleState.moonEffectiveDate.toISOString(), '2026-09-14T18:00:00.000Z');
assert.equal(run(base, 2), base.toISOString(), 'Changing duration resets the clock.');
component._pmndrsTickTimeMs += 60000;
assert.equal(run(base, 2), '2026-09-11T06:00:00.000Z');
const changed = new Date('2026-12-31T23:00:00Z');
assert.equal(run(changed), changed.toISOString(), 'Changing authored date/time resets the clock.');
component._pmndrsTickTimeMs -= 10000;
assert.equal(run(changed), changed.toISOString(), 'A backwards clock cannot advance simulation.');
delete component._pmndrsTickTimeMs;
assert.equal(run(), base.toISOString(), 'Switching from tick to performance time resets state.');
now += 30000;
assert.equal(run(), '2026-09-11T06:00:00.000Z');
component._pmndrsTickTimeMs = NaN;
assert.equal(run(), '2026-09-11T06:00:00.000Z', 'Invalid tick time uses the performance clock.');
component._pmndrsTickTimeMs = 0;
assert.equal(run(base, 0.01), base.toISOString());
component._pmndrsTickTimeMs = 7500;
assert.equal(run(base, 0.01), '2026-09-11T06:00:00.000Z', 'The minimum cycle duration remains 15 seconds.');

const independent = {};
assert.equal(clock.effectiveDate(independent, base, 1).toISOString(), base.toISOString());
assert.notEqual(independent._pmndrsDayNightCycleState, component._pmndrsDayNightCycleState);
const catalog = readFileSync(new URL('./build/runtime-chunks.mjs', import.meta.url), 'utf8');
assert.ok(catalog.includes("masterSource('vrodos_celestial_clock.js')"));
assert.ok(catalog.indexOf("masterSource('vrodos_celestial_clock.js')") < catalog.indexOf("masterSource('vrodos_quality_profiles.js')"));
console.log('Celestial clock behavior passed.');
