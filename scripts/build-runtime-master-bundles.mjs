import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { build } from 'esbuild';
import { browserBuildDefaults, buildBrowserBundle } from './build/esbuild-helpers.mjs';
import {
  createRuntimeBuildManifest,
  generatedRuntimeContractPath,
  runtimeBuildChunks,
  runtimeBuildManifestPath
} from './build/runtime-chunks.mjs';
import {
  fromPluginRoot,
  pluginRoot,
  runtimeLibraryDir,
  toPluginRelative
} from './build/paths.mjs';
import {
  assertReadable,
  validateRuntimeBuildManifest
} from './build/runtime-manifest-validator.mjs';

const contractPath = fromPluginRoot('assets/runtime-settings-contract.json');
const contractOutputPath = fromPluginRoot(generatedRuntimeContractPath);
const manifestPath = fromPluginRoot(runtimeBuildManifestPath);
const spatialUiFontDir = fromPluginRoot('assets/vendor/fonts/noto-sans');
const spatialUiMsdfVendorDir = fromPluginRoot('assets/vendor/zappar-msdf-generator');
const spatialUiMsdfWorkerEntry = fromPluginRoot(
  'node_modules/@zappar/msdf-generator/dist/worker.js'
);
const spatialUiMsdfWasmSource = fromPluginRoot(
  'node_modules/@zappar/msdf-generator/dist/msdfgen_wasm.wasm'
);
const spatialUiMsdfLicenseSource = fromPluginRoot('node_modules/@zappar/msdf-generator/LICENSE');
const spatialUiMsdfWorkerOutput = path.join(spatialUiMsdfVendorDir, 'worker.js');
const spatialUiMsdfWasmOutput = path.join(spatialUiMsdfVendorDir, 'msdfgen_wasm.wasm');
const spatialUiMsdfLicenseOutput = path.join(spatialUiMsdfVendorDir, 'LICENSE');
const generatedBanner =
  '/* Generated by scripts/build-runtime-master-bundles.mjs. Do not edit directly. */';

function runtimeSchemaDefaults(contract) {
  const defaults = {};
  const sceneSettings = contract?.sceneSettings ?? {};

  for (const [key, settingValue] of Object.entries(sceneSettings)) {
    const setting = settingValue || {};
    const value = Object.prototype.hasOwnProperty.call(setting, 'default')
      ? setting.default
      : '';
    defaults[key] = typeof value === 'boolean' ? (value ? '1' : '0') : String(value);
  }

  return defaults;
}

async function buildContract() {
  const parsed = JSON.parse(await readFile(contractPath, 'utf8'));
  const schemaDefaults = runtimeSchemaDefaults(parsed);
  const source = [
    generatedBanner,
    '(function () {',
    `    window.VRODOS_RUNTIME_SETTINGS_CONTRACT = ${JSON.stringify(parsed)};`,
    `    window.VRODOS_RUNTIME_SETTINGS_SCHEMA_DEFAULTS = ${JSON.stringify(schemaDefaults)};`,
    '}());',
    ''
  ].join('\n');

  await writeFile(contractOutputPath, source, 'utf8');
  console.log(`Built ${toPluginRelative(contractOutputPath)}`);
}

async function buildSpatialUiMsdfAssets() {
  await mkdir(spatialUiMsdfVendorDir, { recursive: true });
  await build({
    ...browserBuildDefaults,
    entryPoints: [spatialUiMsdfWorkerEntry],
    format: 'esm',
    outfile: spatialUiMsdfWorkerOutput,
    banner: {
      js: '/* Bundled by scripts/build-runtime-master-bundles.mjs for VRodos spatial UI font atlas generation. */'
    }
  });
  await copyFile(spatialUiMsdfWasmSource, spatialUiMsdfWasmOutput);
  await copyFile(spatialUiMsdfLicenseSource, spatialUiMsdfLicenseOutput);
  console.log(`Built ${toPluginRelative(spatialUiMsdfWorkerOutput)}`);
  console.log(`Copied ${toPluginRelative(spatialUiMsdfWasmOutput)}`);
}

async function readRuntimeSource(relativePath) {
  const source = await readFile(fromPluginRoot(relativePath), 'utf8');
  return `\n/* ===== ${relativePath} ===== */\n${source.trim()}\n`;
}

async function buildConcatenatedChunk(chunk, outputPath) {
  const sources = [];
  for (const sourceFile of chunk.sourceFiles) {
    sources.push(await readRuntimeSource(sourceFile));
  }

  await build({
    ...browserBuildDefaults,
    stdin: {
      contents: sources.join('\n'),
      resolveDir: pluginRoot,
      sourcefile: `${chunk.id}.runtime-concat.js`
    },
    bundle: false,
    outfile: outputPath,
    banner: {
      js: generatedBanner
    }
  });
}

async function buildBundledChunk(chunk, outputPath) {
  await buildBrowserBundle({
    entryPoint: fromPluginRoot(chunk.entryPoint),
    outfile: outputPath,
    banner: {
      js: generatedBanner
    },
    virtualModules: {
      three: {
        globalExpression: 'window.THREE || (window.AFRAME && window.AFRAME.THREE) || {}'
      }
    }
  });
}

async function buildChunk(chunk) {
  const outputPath = path.join(runtimeLibraryDir, chunk.output);
  if (chunk.bundle) {
    await buildBundledChunk(chunk, outputPath);
  } else {
    await buildConcatenatedChunk(chunk, outputPath);
  }
  console.log(`Built ${toPluginRelative(outputPath)}`);
}

async function validateBuildPrerequisites() {
  const prerequisites = [
    [contractPath, 'Runtime settings contract'],
    [path.join(spatialUiFontDir, 'NotoSans-Regular.ttf'), 'Spatial UI Noto Sans regular font'],
    [path.join(spatialUiFontDir, 'NotoSans-Bold.ttf'), 'Spatial UI Noto Sans bold font'],
    [path.join(spatialUiFontDir, 'LICENSE'), 'Spatial UI Noto Sans license'],
    [spatialUiMsdfWorkerEntry, 'Spatial UI MSDF worker source'],
    [spatialUiMsdfWasmSource, 'Spatial UI MSDF WASM source'],
    [spatialUiMsdfLicenseSource, 'Spatial UI MSDF license source']
  ];

  for (const [filePath, label] of prerequisites) {
    await assertReadable(filePath, label);
  }
}

async function validateChunkInputs() {
  for (const chunk of runtimeBuildChunks) {
    if (chunk.entryPoint) {
      await assertReadable(
        fromPluginRoot(chunk.entryPoint),
        `Runtime bundle entry for ${chunk.id}`
      );
    }
    for (const sourceFile of chunk.sourceFiles) {
      await assertReadable(
        fromPluginRoot(sourceFile),
        `Runtime source for ${chunk.id}`
      );
    }
  }
}

async function buildManifest() {
  const manifest = createRuntimeBuildManifest();
  await validateRuntimeBuildManifest(manifest);
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  console.log(`Built ${toPluginRelative(manifestPath)}`);
}

async function main() {
  await mkdir(runtimeLibraryDir, { recursive: true });
  await validateBuildPrerequisites();
  await buildContract();
  await validateChunkInputs();
  await buildSpatialUiMsdfAssets();

  for (const chunk of runtimeBuildChunks) {
    await buildChunk(chunk);
  }

  await buildManifest();
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
